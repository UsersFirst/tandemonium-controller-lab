#!/usr/bin/env node
// ============================================================
// new-element.mjs — scaffold a typed @usersfirst/ui custom element
// ============================================================
//
// Generates everything one element needs so that "add a control" is one
// command and the typed pattern is never hand-copied (and drifted):
//
//   packages/ui/src/elements/<tag>.js      class with typed getters/setters,
//                                          token-only styles, render()
//   packages/ui/src/index.js               export line appended
//   packages/ui/src/elements.d.ts          tag → class entry (typed createElement)
//   packages/ui/gallery.html               a section showing every state
//
//   node tools/ui-kit/new-element.mjs uf-button \
//        --props "label:string='Ride',variant:enum(primary|accent|ghost)=primary,disabled:boolean=false" \
//        --desc "The one button."
//
// Prop grammar:  name:string='default' | name:number=0 | name:boolean=false
//                | name:enum(a|b|c)=a      (first value is the default if = omitted)
// Then: npm run typecheck && npm test -w @usersfirst/ui

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const LAB = path.resolve(HERE, '..', '..');
const UI = path.join(LAB, 'packages', 'ui');

const args = process.argv.slice(2);
const tag = args.find((a) => !a.startsWith('--'));
const opt = (n, d = '') => { const i = args.indexOf(`--${n}`); return i >= 0 ? args[i + 1] : d; };
if (!tag || !/^uf-[a-z][a-z0-9-]*$/.test(tag)) { console.error('usage: new-element.mjs uf-<name> [--props "…"] [--desc "…"]  (tag must be uf-kebab-case)'); process.exit(2); }
const file = path.join(UI, 'src', 'elements', `${tag}.js`);
if (fs.existsSync(file) && !args.includes('--force')) { console.error(`exists: ${path.relative(LAB, file)} (use --force to overwrite the element file only)`); process.exit(2); }

const className = tag.split('-').map((s) => s[0].toUpperCase() + s.slice(1)).join('');
const desc = opt('desc', `${className} — describe me.`);

// ── parse props ──
const props = [];
for (const raw of opt('props').split(',').map((s) => s.trim()).filter(Boolean)) {
  const m = raw.match(/^([a-zA-Z][a-zA-Z0-9]*):(string|number|boolean|enum\(([^)]+)\))(?:=(.*))?$/);
  if (!m) { console.error(`bad prop: "${raw}"`); process.exit(2); }
  const [, name, kind, enumList, defRaw] = m;
  if (kind.startsWith('enum')) {
    const values = enumList.split('|').map((s) => s.trim());
    const def = defRaw ?? values[0];
    if (!values.includes(def)) { console.error(`enum default "${def}" not in ${values.join('|')}`); process.exit(2); }
    props.push({ name, kind: 'enum', values, def, ts: values.map((v) => `'${v}'`).join(' | ') });
  } else if (kind === 'string') props.push({ name, kind, def: defRaw ? defRaw.replace(/^['"]|['"]$/g, '') : '', ts: 'string' });
  else if (kind === 'number') props.push({ name, kind, def: Number(defRaw ?? 0), ts: 'number' });
  else props.push({ name, kind, def: defRaw === 'true', ts: 'boolean' });
}
if (!props.length) props.push({ name: 'label', kind: 'string', def: '', ts: 'string' });

const propLine = (p) => {
  if (p.kind === 'enum') return `    ${p.name}: prop.enum(/** @type {const} */ ([${p.values.map((v) => `'${v}'`).join(', ')}]), '${p.def}'),`;
  if (p.kind === 'string') return `    ${p.name}: prop.string('${p.def.replace(/'/g, "\\'")}'),`;
  return `    ${p.name}: prop.${p.kind}(${JSON.stringify(p.def)}),`;
};
const accessor = (p) => `  /** @returns {${p.ts}} */ get ${p.name}() { return this.get('${p.name}'); }\n  /** @param {${p.ts}} v */ set ${p.name}(v) { this.set('${p.name}', v); }`;
const kebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());

const source = `// @ts-check
// ============================================================
// <${tag}> — ${desc}
// ============================================================
//
// Generated by tools/ui-kit/new-element.mjs. Edit freely — the generator
// never overwrites without --force. Rules of the kit:
//   • colours / sizes / radii come from tokens.css (var(--uf-*)); no literals
//   • light DOM: the page's CSS + FocusController can reach inside
//   • state lives in props (attributes); render() is a pure function of them
//   • outbound: this.emit('${tag}:<event>', detail)

import { UfElement, prop, esc } from '../uf-element.js';

export class ${className} extends UfElement {
  /** @override */ static tag = '${tag}';

  /** @override */ static props = {
${props.map(propLine).join('\n')}
  };

  /** @override */ static styles = \`
    ${tag} { display: inline-block; font: var(--uf-size-md)/1.3 var(--uf-font-ui); color: var(--uf-color-fg); }
  \`;

${props.map(accessor).join('\n\n')}

  /** @override */
  render() {
    return \`<span class="${tag}__body">\${esc(this.${props[0].name})}</span>\`;
  }
}

${className}.define();
`;

fs.writeFileSync(file, source);

// index.js export
const indexPath = path.join(UI, 'src', 'index.js');
let index = fs.readFileSync(indexPath, 'utf8');
const exportLine = `export { ${className} } from './elements/${tag}.js';`;
if (!index.includes(exportLine)) index = index.replace(/(\/\/ uf:elements[^\n]*\n)/, `$1${exportLine}\n`), fs.writeFileSync(indexPath, index);

// elements.d.ts
const dtsPath = path.join(UI, 'src', 'elements.d.ts');
let dts = fs.readFileSync(dtsPath, 'utf8');
const imp = `import type { ${className} } from './elements/${tag}.js';`;
if (!dts.includes(imp)) {
  dts = dts.replace('// uf:elements-imports', `// uf:elements-imports\n${imp}`);
  dts = dts.replace('    // uf:elements-map', `    // uf:elements-map\n    '${tag}': ${className};`);
  fs.writeFileSync(dtsPath, dts);
}

// gallery section: one state per enum value / boolean on-off, defaults otherwise
const galleryPath = path.join(UI, 'gallery.html');
let gallery = fs.readFileSync(galleryPath, 'utf8');
if (!gallery.includes(`<section id="${tag}">`)) {
  const attrs = (over = {}) => props.map((p) => {
    const v = p.name in over ? over[p.name] : p.def;
    if (p.kind === 'boolean') return v ? kebab(p.name) : '';
    return `${kebab(p.name)}="${String(v).replace(/"/g, '&quot;')}"`;
  }).filter(Boolean).join(' ');
  const states = [{ label: 'default', over: {} }];
  for (const p of props) {
    if (p.kind === 'enum') for (const v of p.values) if (v !== p.def) states.push({ label: `${p.name}=${v}`, over: { [p.name]: v } });
    if (p.kind === 'boolean') states.push({ label: `${p.name}=${!p.def}`, over: { [p.name]: !p.def } });
  }
  const section = `<section id="${tag}">
  <h2>&lt;${tag}&gt; · ${esc(desc)}</h2>
  <div class="states">
${states.map((s) => `    <div class="state"><${tag} ${attrs(s.over)}></${tag}><small>${esc(s.label)}</small></div>`).join('\n')}
  </div>
</section>

<!-- uf:elements -->`;
  gallery = gallery.replace('<!-- uf:elements -->', section);
  fs.writeFileSync(galleryPath, gallery);
}
function esc(s) { return String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c])); }

// screenboard: capture the new section as its own screen
const manPath = path.join(LAB, 'tools', 'screenboard', 'manifests', 'ui-gallery.json');
if (fs.existsSync(manPath)) {
  const man = JSON.parse(fs.readFileSync(manPath, 'utf8'));
  if (!man.screens.some((s) => s.id === tag)) { man.screens.push({ id: tag, title: `Gallery · <${tag}>`, clip: `#${tag}`, ops: [] }); fs.writeFileSync(manPath, JSON.stringify(man, null, 2) + '\n'); }
}

console.log(`[ui-kit] created ${path.relative(LAB, file)}
[ui-kit] exported from packages/ui/src/index.js, typed in elements.d.ts, section added to gallery.html, screen added to ui-gallery manifest
[ui-kit] next: edit render()/styles, then  npm run typecheck && npm test -w @usersfirst/ui && npm run ui:screenboard -- --manifest ui-gallery`);
